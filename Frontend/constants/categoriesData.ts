/**
 * Returns the authoritative fixed XP for a given category and subcategory.
 * Matches backend XP mapping exactly.
 */
export function getSubcategoryXp(categoryName?: string | null, subcategoryName?: string | null): number | null {
  if (!categoryName || !subcategoryName) return null;

  const cat = CATEGORY_XP_MAP[categoryName.trim()];
  if (cat && typeof cat[subcategoryName.trim()] === 'number') {
    return cat[subcategoryName.trim()];
  }

  // Case-insensitive fallback
  const lowerCat = categoryName.trim().toLowerCase();
  const lowerSub = subcategoryName.trim().toLowerCase();
  for (const [cName, subMap] of Object.entries(CATEGORY_XP_MAP)) {
    if (cName.toLowerCase() === lowerCat) {
      for (const [sName, xp] of Object.entries(subMap)) {
        if (sName.toLowerCase() === lowerSub) {
          return xp;
        }
      }
    }
  }

  return null;
}

export function searchCategories(query: string): { mainCategory: MainCategory; matchingSubcategories: string[] }[] {
  if (!query || query.trim() === '') {
    return CATEGORIES_DATA.map(cat => ({
      mainCategory: cat,
      matchingSubcategories: cat.subcategories,
    }));
  }

  const q = query.toLowerCase().trim();
  const results: { mainCategory: MainCategory; matchingSubcategories: string[] }[] = [];

  for (const cat of CATEGORIES_DATA) {
    const mainMatches = cat.name.toLowerCase().includes(q);
    const matchingSubs = cat.subcategories.filter(sub => sub.toLowerCase().includes(q));

    if (mainMatches || matchingSubs.length > 0) {
      results.push({
        mainCategory: cat,
        matchingSubcategories: mainMatches ? cat.subcategories : matchingSubs,
      });
    }
  }

  return results;
}
